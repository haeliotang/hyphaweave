_KEYS_BY_ID: dict[str, keyutil.KeyMaterial] | None = None


def _keys_by_id() -> dict[str, keyutil.KeyMaterial]:
    """All generated test keys indexed by key id (for the generator self-check)."""
    global _KEYS_BY_ID
    if _KEYS_BY_ID is None:
        table: dict[str, keyutil.KeyMaterial] = {}
        for meta_path in sorted(recordlib.KEYS_DIR.glob("*.json")):
            material = recordlib.key(meta_path.stem)
            table[material.key_id] = material
        _KEYS_BY_ID = table
    return _KEYS_BY_ID


def _selfcheck_signatures(record: dict[str, Any], *, context: str) -> None:
    """Prove that every present signature really verifies (independent check)."""
    entries = record.get("sigs")
    if entries is None:
        return
    keys = [entry["key"] for entry in entries]
    if keys != sorted(keys) or len(set(keys)) != len(keys):
        raise SystemExit("%s: sigs are not sorted/unique in a positive case" % context)
    for entry in entries:
        material = _keys_by_id().get(entry["key"])
        if material is None:
            raise SystemExit(
                "%s: positive case references undeclared key %r"
                % (context, entry["key"])
            )
        signature = keyutil.b64url_decode(entry["value"], expected_len=64)
        if not keyutil.verify(
            material.public_raw, recordlib.sig_message(record), signature
        ):
            raise SystemExit("%s: positive case has an invalid signature" % context)


def selfcheck_case(case: Case, files: dict[str, bytes]) -> None:
    """Independent structural self-check for cases expected to be valid/erased."""
    if case.verdict not in {"valid", "erased"}:
        return
    if case.target == "record":
        record = wcj.parse_strict(files[case.input])
        if case.verdict == "erased":
            if record.get("kind") != "weave.erased":
                raise SystemExit("%s: erased case is not a weave.erased placeholder" % case.id)
            return
        _selfcheck_signatures(record, context=case.id)
        return
    prefix = case.input + "/"
    manifest_path = prefix + "manifest.json"
    if manifest_path not in files:
        raise SystemExit("%s: valid container case has no manifest.json" % case.id)
    manifest = wcj.parse_strict(files[manifest_path])
    manifest_digest = recordlib.manifest_digest(files[manifest_path])
    listed: dict[str, str] = {}
    for entry in manifest["records"]:
        digest = entry["digest"]
        listed[digest] = entry["id"]
        path = prefix + "records/%s.json" % digest[len("sha256:") :]
        if path not in files:
            raise SystemExit("%s: positive case is missing %s" % (case.id, path))
        record = wcj.parse_strict(files[path])
        actual = recordlib.record_digest(record)
        if actual != digest:
            raise SystemExit(
                "%s: record digest mismatch for %s (%s != %s)"
                % (case.id, path, actual, digest)
            )
        _selfcheck_signatures(record, context=case.id + ":" + entry["id"])
    sigfile_path = prefix + "signatures/manifest.sig.json"
    sigfile = wcj.parse_strict(files[sigfile_path])
    if sigfile["digest"] != manifest_digest:
        raise SystemExit("%s: manifest digest does not match the manifest bytes" % case.id)
    message = recordlib.sig_message_for_manifest(manifest_digest)
    for entry in sigfile["signatures"]:
        material = _keys_by_id().get(entry["key"])
        if material is None:
            raise SystemExit("%s: manifest signed by unknown key" % case.id)
        if not keyutil.verify(
            material.public_raw,
            message,
            keyutil.b64url_decode(entry["value"], expected_len=64),
        ):
            raise SystemExit("%s: positive manifest signature does not verify" % case.id)


_KEY_NAMES_BY_ID: dict[str, str] | None = None


def _key_names_by_id() -> dict[str, str]:
    global _KEY_NAMES_BY_ID
    if _KEY_NAMES_BY_ID is None:
        table: dict[str, str] = {}
        for meta_path in sorted(recordlib.KEYS_DIR.glob("*.json")):
            material = recordlib.key(meta_path.stem)
