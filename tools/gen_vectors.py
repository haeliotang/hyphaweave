def _ref_container(*, claim_kind: str, ref_digest: str | None = None, target_id: str = "ref-target") -> dict[str, bytes]:
    """Two records in one container: a target note and a record referencing it."""
    target = recordlib.note(target_id)
    target_digest = recordlib.record_digest(target)
    source = recordlib.note(
        "ref-source",
        refs=[
            {
                "rel": "supersedes",
                "ref": recordlib.make_ref(
                    target["origin"]["instance"],
                    target["id"],
                    ref_digest if ref_digest is not None else target_digest,
                    kind=claim_kind,
                ),
            }
        ],
    )
    return build_container([target, source])


