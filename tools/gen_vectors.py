@dataclass
class Case:
    category: str
    name: str
    target: str
    input: str
    verdict: str
    build: Callable[[], dict[str, bytes]]
    errors: tuple[str, ...] = ()
    notices: tuple[str, ...] = ()
    args: tuple[str, ...] = ()
    notes: str = ""
    expected_digest: str = ""  # "auto" = computed from the built input record
    expected_resolution: tuple[str, ...] | None = None
    expected_container: dict[str, Any] | None = None
    records: tuple[dict[str, Any], ...] | None = None

    @property
    def id(self) -> str:
        return "%s/%s" % (self.category, self.name)


CASES: list[Case] = []


def declare(
    category: str,
    name: str,
    target: str,
    input_value: str,
    verdict: str,
    *,
    build: Callable[[], dict[str, bytes]],
    **kwargs: Any,
) -> None:
    CASES.append(
        Case(
            category=category,
            name=name,
            target=target,
            input=input_value,
            verdict=verdict,
            build=build,
            **kwargs,
        )
    )


