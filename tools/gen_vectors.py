def rec(record: dict[str, Any], filename: str = "record.json") -> dict[str, bytes]:
    return {filename: recordlib.canonical_file(record)}


def raw(data: bytes, filename: str = "record.json") -> dict[str, bytes]:
    return {filename: data}


def publish(record: dict[str, Any], signers: str | Sequence[str] | None = None) -> dict[str, bytes]:
    if signers is not None:
        record = recordlib.signed(record, signers)
    return rec(record)


def seq(*parts: dict[str, bytes]) -> dict[str, bytes]:
    merged: dict[str, bytes] = {}
    for part in parts:
        merged.update(part)
    return merged


def container(files: dict[str, bytes]) -> dict[str, bytes]:
    """Wrap a container file map under the case-relative ``container/`` dir."""
    return {"container/" + name: data for name, data in files.items()}


def build_container(records: Sequence[dict[str, Any]], **kwargs: Any) -> dict[str, bytes]:
    return container(recordlib.build_container(records, **kwargs))


def pretty(value: Any) -> bytes:
    """Non-canonical pretty-printed JSON (whitespace violates WR-CJ §1.8)."""
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def compact_unsorted(value: Any) -> bytes:
    """Non-canonical order-preserving compact JSON (wrong member order)."""
    return (json.dumps(value, separators=(",", ":"), ensure_ascii=False) + "\n").encode(
        "utf-8"
    )


def replace_once(data: bytes, needle: bytes, replacement: bytes) -> bytes:
    if data.count(needle) != 1:
        raise ValueError("expected exactly one occurrence of %r" % needle)
    return data.replace(needle, replacement)


def without(record: dict[str, Any], *names: str) -> dict[str, Any]:
    return {key: value for key, value in record.items() if key not in names}


def with_field(record: dict[str, Any], name: str, value: Any) -> dict[str, Any]:
    result = dict(record)
    result[name] = value
    return result


def _last_b64_char_violation(value: str) -> str:
    """Return *value* with non-zero base64url unused trailing bits.

    Both 16-byte salts (22 chars) and 64-byte signatures (86 chars) end in a
    character carrying four unused trailing bits; canonical encodings have
    those bits zero, so setting one of them produces a non-canonical string.
    """
    alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
    index = alphabet.index(value[-1])
    return value[:-1] + alphabet[(index & ~15) + 1]


def _key(name: str) -> keyutil.KeyMaterial:
    return recordlib.key(name)


def _kid(name: str) -> str:
    return recordlib.kid(name)


def _sig_entry_for_message(name: str, message: bytes) -> dict[str, str]:
    material = _key(name)
    return {
        "alg": "ed25519",
        "key": material.key_id,
        "value": keyutil.b64url_encode(material.sign(message)),
    }


def wrong_signature(
    record: dict[str, Any],
    *,
    key_name: str = "human-1",
    message: Callable[[dict[str, Any]], bytes] | None = None,
) -> dict[str, str]:
    """A signature entry over the wrong message/domain for *record*."""
    digest = recordlib.record_digest(record)
    if message is None:
        payload = SIG_DOMAIN_WRONG + digest.encode("ascii")
    else:
        payload = message(record)
    return _sig_entry_for_message(key_name, payload)


def patched_sig(
    record: dict[str, Any],
    *,
    key_name: str = "human-1",
    tamper: Callable[[bytes], bytes],
) -> list[dict[str, str]]:
    """A genuine signature for *record* with its raw 64 bytes tampered."""
    material = _key(key_name)
    raw_signature = material.sign(recordlib.sig_message(record))
    return [
        {
            "alg": "ed25519",
            "key": material.key_id,
            "value": keyutil.b64url_encode(tamper(raw_signature)),
        }
    ]


def set_sigs(record: dict[str, Any], entries: Sequence[dict[str, str]]) -> dict[str, Any]:
    result = dict(record)
    result["sigs"] = list(entries)
    return result


