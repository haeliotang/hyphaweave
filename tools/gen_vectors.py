"""Generate the core ``weave-record/1`` conformance vectors under ``vectors/``.

Scope: categories ``jcs``, ``digest``, ``sig``, ``ref``, ``stage``, ``actor``
and ``labels``.  The remaining categories (``erasure``, ``grant``,
``key-lifecycle``, ``container``, ``integrity-levels``) are generated by
``tools/gen_vectors_extra.py``; ``vectors/index.json`` is produced afterwards
by ``tools/gen_index.py`` from every case directory on disk.

Every case is declared in the table below with a **hand-authored** expected
verdict and expected error codes (read off the contract, never obtained by
running the reference verifier).  Input files are built with the independent
helpers under ``tools/``: :mod:`wcj` (own WR-CJ v1 implementation),
:mod:`keyutil` (own base64url/key-id/Ed25519 helpers) and :mod:`recordlib`
(own record/container construction).  The generator must never import, run or
otherwise consult ``hyphaweave_verify``.

Usage (from the repository root)::

    ./.venv/bin/python tools/gen_vectors.py            # regenerate
    ./.venv/bin/python tools/gen_vectors.py --check    # verify on-disk copy
"""

