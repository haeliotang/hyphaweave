def root_grant(
    *,
    grant_id: str = "grant-1",
    grantee: str = "agent-1",
    kinds: Sequence[str] = ("example.note",),
    actions: Sequence[str] = ("propose",),
    scope: Sequence[str] = ("test-scope",),
    valid_from: str = recordlib.T0,
    valid_until: str | None = None,
    transferable: bool = False,
    signer: str = "human-1",
    recorded_at: str = recordlib.T0,
) -> dict[str, Any]:
    """A valid root ``weave.grant`` record (signed by a human key)."""
    body = {
        "action": "grant",
        "grant": {
            "grantee": {"key": _kid(grantee)},
            "kinds": list(kinds),
            "actions": list(actions),
            "scope": list(scope),
            "valid_from": valid_from,
            "valid_until": valid_until,
            "transferable": transferable,
            "evidence": None,
            "remedy": None,
        },
    }
    record = recordlib.build_record(
        kind="weave.grant",
        id=grant_id,
        actor=recordlib.actor(signer),
        body=body,
        stage="accepted",
        recorded_at=recorded_at,
    )
    return recordlib.signed(record, signer)


