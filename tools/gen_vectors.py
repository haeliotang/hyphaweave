def agent_note(
    record_id: str,
    *,
    stage: str = "proposed",
    key_name: str = "agent-1",
    grant: dict[str, Any] | None = None,
    recorded_at: str = recordlib.T0,
    body: dict[str, Any] | None = None,
    idempotency_key: str | None = None,
) -> dict[str, Any]:
    """An agent actor record of the unregistered kind ``example.note``."""
    actor = recordlib.agent_actor(
        key_name,
        grant=grant_ref(grant) if grant is not None else None,
        idempotency_key=(
            idempotency_key if idempotency_key is not None else "idem-" + record_id
        ),
    )
    record = recordlib.build_record(
        kind="example.note",
        id=record_id,
        actor=actor,
        body=body if body is not None else {"text": "synthetic agent note"},
        stage=stage,
        recorded_at=recorded_at,
    )
    return recordlib.signed(record, key_name)


