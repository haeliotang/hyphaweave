# Positive record cases that are *deliberately* unsigned: they exist to prove
# that an unsigned (container-covered) record can be valid, so gate 3(a) cannot
# demand a cryptographic binding for them. Documented in GATE-3-EXCEPTIONS.md.
UNSIGNED_POSITIVE_EXCEPTIONS = frozenset(
    {
        "digest/record-unsigned",
        "stage/valid-proposed-unsigned",
    }
)


def bind_positive_record(case: Case, files: dict[str, bytes]) -> dict[str, bytes]:
    """Attach the actor's real signature to unsigned record-target positives.

    Gate 3(a) flips one bit of every positive input and requires the verifier
    never to return ``valid``; a signed record makes any canonical-byte change
    fail the digest/signature binding (a flip inside ``sigs`` keeps the digest
    but breaks the signature). The record digest excludes ``sigs``, so adding a
    signature never changes ``expected_digest``.
    """
    if case.target != "record" or case.verdict not in {"valid", "erased"}:
        return files
    if case.id in UNSIGNED_POSITIVE_EXCEPTIONS:
        return files
    data = files[case.input]
    try:
        record = wcj.parse_strict(data)
    except wcj.WcjError:
        return files  # defensive: a positive must be canonical
    if record.get("kind") == "weave.erased" or "sigs" in record:
        return files
    key_name = _key_names_by_id()[record["actor"]["key"]]
    signed_record = recordlib.signed(record, key_name)
    trailing_lf = data.endswith(b"\n")
    bound = wcj.canonicalize(signed_record) + (b"\n" if trailing_lf else b"")
    result = dict(files)
    result[case.input] = bound
    if not case.args:
        case.args = ("--keys", "@keyset")
    return result


def build_expected(case: Case, files: dict[str, bytes]) -> dict[str, Any]:
    expected: dict[str, Any] = {
        "id": case.id,
        "category": case.category,
        "target": case.target,
        "input": case.input,
        "verdict": case.verdict,
        "errors": list(case.errors),
    }
    if case.notices:
        expected["notices"] = list(case.notices)
    if case.args:
        expected["args"] = list(case.args)
    if case.expected_digest:
        if case.expected_digest != "auto" or case.target != "record":
            raise SystemExit("%s: unsupported expected_digest declaration" % case.id)
        record = wcj.parse_strict(files[case.input])
        expected["expected_digest"] = recordlib.record_digest(record)
    if case.expected_resolution is not None:
        expected["expected_resolution"] = list(case.expected_resolution)
    if case.expected_container is not None:
        expected["expected_container"] = case.expected_container
    if case.records is not None:
        expected["records"] = list(case.records)
    if case.notes:
        expected["notes"] = case.notes
    return expected


def case_files(case: Case) -> tuple[dict[str, bytes], dict[str, Any]]:
    files = bind_positive_record(case, case.build())
    if case.target == "container":
        prefix = case.input + "/"
        if case.input not in files and not any(
            name.startswith(prefix) for name in files
        ):
            raise SystemExit(
                "%s: container input %r is not among the built case files (%s)"
                % (case.id, case.input, sorted(files))
            )
    elif case.input not in files:
        raise SystemExit(
            "%s: input %r is not among the built files (%s)"
            % (case.id, case.input, sorted(files))
        )
    for name in files:
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts:
            raise SystemExit("%s: unsafe case file path %r" % (case.id, name))
    selfcheck_case(case, files)
    return files, build_expected(case, files)


def validate_case(case: Case) -> None:
    if case.verdict not in {"valid", "invalid", "unverifiable", "erased"}:
        raise SystemExit("%s: invalid verdict %r" % (case.id, case.verdict))
    if case.verdict == "invalid" and not case.errors:
        raise SystemExit("%s: invalid case must name expected error codes" % case.id)
    if case.verdict == "valid" and case.errors:
        raise SystemExit("%s: valid case may not expect error codes" % case.id)
    if case.target not in {"record", "container"}:
        raise SystemExit("%s: invalid target %r" % (case.id, case.target))


