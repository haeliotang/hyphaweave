def _prune_stale_case_dirs(expected_by_category: dict[str, set[str]]) -> None:
    """Remove case directories from this generator's categories that no longer exist.

    The other categories are owned by ``tools/gen_vectors_extra.py`` and are
    never touched here.
    """
    for category, names in expected_by_category.items():
        category_dir = VECTORS_DIR / category
        if not category_dir.is_dir():
            continue
        for path in sorted(category_dir.iterdir()):
            if path.is_dir() and path.name not in names:
                for child in sorted(path.rglob("*"), reverse=True):
                    if child.is_file() or child.is_symlink():
                        child.unlink()
                    elif child.is_dir():
                        child.rmdir()
                path.rmdir()


def write_all(*, check: bool) -> list[str]:
    problems: list[str] = []
    seen: set[str] = set()
    expected_by_category: dict[str, set[str]] = {}
    for case in CASES:
        expected_by_category.setdefault(case.category, set()).add(case.name)
    for case in CASES:
        validate_case(case)
        if case.id in seen:
            raise SystemExit("duplicate case id %r" % case.id)
        seen.add(case.id)
        files, expected = case_files(case)
        expected_bytes = wcj.dump_canonical_file(expected)
        target_files = dict(files)
        target_files["expected.json"] = expected_bytes
        case_dir = VECTORS_DIR / case.category / case.name
        if check:
            if not case_dir.is_dir():
                problems.append("missing case dir %s" % case_dir)
                continue
            existing = {
                str(path.relative_to(case_dir)): path.read_bytes()
                for path in case_dir.rglob("*")
                if path.is_file()
            }
            for name, data in sorted(target_files.items()):
                if name not in existing:
                    problems.append("missing %s/%s" % (case_dir, name))
                elif existing[name] != data:
                    problems.append("content mismatch %s/%s" % (case_dir, name))
            for name in sorted(existing):
                if name not in target_files:
                    problems.append("unexpected file %s/%s" % (case_dir, name))
            continue
        if case_dir.exists():
            for path in sorted(case_dir.rglob("*"), reverse=True):
                if path.is_file() or path.is_symlink():
                    path.unlink()
                elif path.is_dir():
                    path.rmdir()
        case_dir.mkdir(parents=True, exist_ok=True)
        for name, data in target_files.items():
            destination = case_dir / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(data)
    if not check:
        _prune_stale_case_dirs(expected_by_category)
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare regenerated output with files on disk (exit 1 on drift)",
    )
    arguments = parser.parse_args(argv)
    problems = write_all(check=arguments.check)
    if "hyphaweave_verify" in sys.modules:  # hard rule: generators never import it
        raise SystemExit("vector generator imported the reference verifier")
    if problems:
        for problem in problems:
            print("FAIL: %s" % problem, file=sys.stderr)
        return 1
    if arguments.check:
        print("ok: %d vector cases match the generator" % len(CASES))
    else:
        print("wrote %d vector cases under vectors/" % len(CASES))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
