"""Build ``vectors/index.json`` — the catalog of every conformance vector case.

The index is generated from the case directories on disk (``expected.json`` in
``vectors/<category>/<case-id>/``) so that it also covers the categories
generated by ``tools/gen_vectors_extra.py``.  Run this after every generator:

    ./.venv/bin/python tools/gen_vectors.py
    ./.venv/bin/python tools/gen_vectors_extra.py
    ./.venv/bin/python tools/gen_index.py            # writes the index
    ./.venv/bin/python tools/gen_index.py --check    # verify, exit 1 on drift

Each ``expected.json`` is required to be WR-CJ canonical JSON (`vectors/README.md`).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

_TOOLS_DIR = Path(__file__).resolve().parent
if str(_TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(_TOOLS_DIR))

import wcj

REPO_ROOT = _TOOLS_DIR.parent
VECTORS_DIR = REPO_ROOT / "vectors"

CATEGORIES = (
    "jcs",
    "digest",
    "sig",
    "ref",
    "stage",
    "actor",
    "labels",
    "erasure",
    "grant",
    "key-lifecycle",
    "container",
    "integrity-levels",
)

REQUIRED_FIELDS = ("id", "category", "target", "input", "verdict")
VERDICTS = frozenset({"valid", "invalid", "unverifiable", "erased"})
TARGETS = frozenset({"record", "container"})


def read_case_expected(path: Path) -> dict[str, Any]:
    try:
        data = path.read_bytes()
    except OSError as exc:
        raise SystemExit("cannot read %s: %s" % (path, exc))
    try:
        value = wcj.parse_strict(data)
    except wcj.WcjError as exc:
        raise SystemExit("%s is not canonical WR-CJ JSON: %s" % (path, exc))
    if not isinstance(value, dict):
        raise SystemExit("%s: expected.json must be a JSON object" % path)
    return value


def collect_cases() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    for category in CATEGORIES:
        category_dir = VECTORS_DIR / category
        if not category_dir.is_dir():
            continue
        for case_dir in sorted(path for path in category_dir.iterdir() if path.is_dir()):
            expected_path = case_dir / "expected.json"
            if not expected_path.is_file():
                raise SystemExit(
                    "case directory without expected.json: %s" % case_dir
                )
            expected = read_case_expected(expected_path)
            for name in REQUIRED_FIELDS:
                if name not in expected:
                    raise SystemExit(
                        "%s: missing required field %r" % (expected_path, name)
                    )
            case_id = expected["id"]
            wanted_id = "%s/%s" % (category, case_dir.name)
            if case_id != wanted_id:
                raise SystemExit(
                    "%s: id %r does not match directory (%r)"
                    % (expected_path, case_id, wanted_id)
                )
            if not isinstance(expected["category"], str) or expected["category"] != category:
                raise SystemExit("%s: category field does not match directory" % expected_path)
            if expected["target"] not in TARGETS:
                raise SystemExit("%s: invalid target %r" % (expected_path, expected["target"]))
            if expected["verdict"] not in VERDICTS:
                raise SystemExit(
                    "%s: invalid verdict %r" % (expected_path, expected["verdict"])
                )
            errors = expected.get("errors", [])
            notices = expected.get("notices", [])
            for name, values in (("errors", errors), ("notices", notices)):
                if not isinstance(values, list) or not all(
                    isinstance(item, str) for item in values
                ):
                    raise SystemExit(
                        "%s: %r must be an array of strings" % (expected_path, name)
                    )
            if expected["verdict"] == "invalid" and not errors:
                raise SystemExit(
                    "%s: invalid case must name expected error codes" % expected_path
                )
            if expected["verdict"] == "valid" and errors:
                raise SystemExit(
                    "%s: valid case may not expect error codes" % expected_path
                )
            if case_id in seen:
                raise SystemExit("duplicate case id %r" % case_id)
            seen.add(case_id)
            rows.append(
                {
                    "id": case_id,
                    "category": category,
                    "target": expected["target"],
                    "input": expected["input"],
                    "verdict": expected["verdict"],
                    "errors": list(errors),
                    "notices": list(notices),
                }
            )
    return rows


def cat_counts(rows: list[dict[str, Any]]) -> dict[str, int]:
    counts = {category: 0 for category in CATEGORIES}
    for row in rows:
        counts[row["category"]] += 1
    return counts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare the generated index with vectors/index.json (exit 1 on drift)",
    )
    arguments = parser.parse_args(argv)
    rows = collect_cases()
    document = {
        "format": "weave-record-vectors/1",
        "spec": "weave-record/1",
        "case_count": len(rows),
        "cases": rows,
    }
    data = wcj.dump_canonical_file(document)
    index_path = VECTORS_DIR / "index.json"
    if arguments.check:
        if not index_path.is_file():
            print("FAIL: missing %s" % index_path, file=sys.stderr)
            return 1
        if index_path.read_bytes() != data:
            print("FAIL: %s is out of date" % index_path, file=sys.stderr)
            return 1
        print("ok: vectors/index.json is up to date (%d cases)" % len(rows))
        return 0
    index_path.write_bytes(data)
    counts = cat_counts(rows)
    summary = ", ".join(
        "%s=%d" % (category, counts[category])
        for category in CATEGORIES
        if counts[category]
    )
    print("wrote %s: %d cases (%s)" % (index_path, len(rows), summary))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
